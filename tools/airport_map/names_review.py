"""One review file for every taxiway-name difference across all airports: chart-only, OSM-only and
conflicting names, each with where it is and what OSM has nearby, so they can be decided in one pass. Stdlib only.

  python3 tools/airport_map/names_review.py      # -> docs/TAXIWAY_NAMES_REVIEW.md (KATL first, then by ICAO)
"""
import collections, json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FIRST = ['KATL']   # Atlanta first


def osm_ways(base):
    p = base / 'osm/osm_aeroways.geojson'   # the full OSM extract (the map layer hides non-chart refs, R1)
    if not p.exists():
        return {}
    by = collections.defaultdict(list)
    for f in json.loads(p.read_text())['features']:
        ref = (f.get('properties') or {}).get('ref')
        if ref and f['geometry']['type'] == 'LineString' and f['properties'].get('aeroway') in ('taxiway', 'taxilane'):
            cs = f['geometry']['coordinates']; mid = cs[len(cs) // 2]
            by[ref].append((round(mid[1], 6), round(mid[0], 6)))
    return by


def main():
    icaos = sorted(p.name.upper() for p in (REPO / 'data/airports').iterdir() if (p / 'review/osm_names_report.json').exists())
    icaos = [i for i in FIRST if i in icaos] + [i for i in icaos if i not in FIRST]
    L = ['# Taxiway names to review, all airports (one pass)', '',
         'Generated by `tools/airport_map/names_review.py` from each airport\'s `review/osm_names_report.json`. Chart label → ground position via the graticule fit; '
         'An OSM ref within ~3 mm at chart scale (R2) counts as a match. Every row carries Franco\'s decision (Oct 9) and the rule that applied:', '',
         '- **R1** the FAA chart is authoritative; OSM is geometry only and never adds or renames a name; parser vocabulary = chart names only',
         '- **R2** match radius = ~3 mm on paper at the chart scale · **R3** standalone X = closed_marker · **R4** OSM way within radius has no ref → chart right (OSM way "unnamed in OSM")',
         '- **R5** nearest OSM ref differs (sub-connector, number, alley) → chart right · **R6** OSM-only refs → ramp/non-movement or uncharted OSM name → ignore (never displayed, never in the parser); if the chart prints it, it was our extraction miss and was fixed',
         '- **R7** labels drawn twice at one spot count once · **R8** agency/facility names are area labels · **R9** KPDK: no decisions until its outline text is decoded', '',
         'Map: `http://localhost:8765/airport_map.html?icao=<icao>` (OSM layer toggle on). Coordinates are WGS84 lat, lon.', '']
    total = collections.Counter()
    for icao in icaos:
        base = REPO / 'data/airports' / icao.lower(); r = json.loads((base / 'review/osm_names_report.json').read_text()); s = r['summary']
        rv = json.loads((base / 'review.json').read_text()); st = next(i['status'] for i in rv['items'] if i['id'] == 'taxiway_names')
        signed = ' (signed, display only)' if rv.get('sign_off') else ''
        rows = [x for x in r['review_list']]; ways = osm_ways(base)
        L.append(f'## {icao}{signed}: taxiway_names = {st}')
        if not any(l for l in json.loads((base / 'review/taxiway_vocabulary.json').read_text())['taxiways']) if (base / 'review/taxiway_vocabulary.json').exists() else False:
            L += ['', 'R9: not a review item yet. This chart has no text layer; its outline text is not decoded into labels yet. No decisions.', '']
            continue
        L.append(f'Matched: {len(s["matched"])}. Chart-only: {len(s["chart_only"])}. Conflicting: {len(s["conflicting"])}. OSM-only: {len(s["osm_only"])}. Label instances to look at: {len(rows)}.')
        if not rows and not s['osm_only']:
            L.append('\nNothing to review.')
        if rows:
            L += ['', '| # | chart label | issue | at (lat, lon) | nearest OSM (ref, m) | decision | rule |', '|---|---|---|---|---|---|---|']
            for k, x in enumerate(rows, 1):
                near = ', '.join(f"{n['ref'] or '(no ref)'} {n['dist_m']:.0f}" for n in x.get('nearest_osm', [])[:3])
                issue = 'conflict: a different ref is closer' if x['status'] == 'conflict' else 'no OSM way with this ref within the radius' if x['status'].startswith('no_osm') else x['status']
                if x['label'] in s['chart_only']:
                    issue = 'chart-only (no OSM way has this ref)'
                dec = x.get('decision', '')
                if x.get('rule') == 'crop':
                    dec = f"**pending** ({x.get('question', '')}); crop `{x.get('crop_file', '')}`"
                L.append(f"| {k} | **{x['label']}** | {issue} | {x['lat']:.6f}, {x['lon']:.6f} | {near} | {dec} | {x.get('rule', '')} |")
        if s['osm_only']:
            L += ['', '| OSM-only ref | OSM ways | e.g. at (lat, lon) | decision | rule |', '|---|---|---|---|---|']
            cls = r.get('osm_only_classified', {})
            for ref in s['osm_only']:
                w = ways.get(ref, []); c = cls.get(ref, '')
                dec = ('ignore: ramp / non-movement' + (' (the chart prints it as a ramp label)' if 'printed' in c else '') if c.startswith('ramp') else
                       'ignore: uncharted OSM name' if c == 'uncharted_osm_name' else '**our extraction/matching miss** (the chart prints it): to fix' if c == 'chart_text_has_it' else '')
                L.append(f"| {ref} | {len(w)} | {w[0][0]:.6f}, {w[0][1]:.6f} | {dec} | R6 |" if w else f'| {ref} | ? | | {dec} | R6 |')
        hn_p = base / 'review/human_notes.json'; hn = json.loads(hn_p.read_text()) if hn_p.exists() else {}
        for oi in hn.get('open_items', []):
            L.append(f"\n**Open (not a taxiway row): {oi['label']}**: {oi['status']}. {oi['note']}")
        for f in hn.get('osm_name_flags', []):
            L.append(f"\nGraph-draft flag: {('OSM way ' + str(f['osm_way']) + ': ') if f.get('osm_way') else ''}{f['flag']} (chart {f['label']})")
        g = r.get('gate_leadins', {})
        if g.get('chart_gates'):
            L.append(f"\nGate lead-ins (Franco, Oct 8: destination only): chart gates {len(g['chart_gates'])}, chart-only {g['chart_only']}, OSM-only {g['osm_only']}.")
        L.append('')
        total.update(chart_only=len(s['chart_only']), conflicting=len(s['conflicting']), osm_only=len(s['osm_only']), instances=len(rows))
    L.insert(6, f"**Totals:** {total['instances']} chart label instances, {total['chart_only']} chart-only names, {total['conflicting']} conflicting names, {total['osm_only']} OSM-only refs across {len(icaos)} airports.\n")
    (REPO / 'docs/TAXIWAY_NAMES_REVIEW.md').write_text('\n'.join(L) + '\n'); print(dict(total), icaos)


if __name__ == '__main__':
    main()
