"""'New this weekend' commit log for the pitch. Judges discount prior work; this makes the new work
visible with timestamps: one Markdown table per day of every commit since --since on the given branches, with files changed.

  python3 tools/weekend_log.py                                   # 00:00 ET, branches weekend/parser-ft + cloud/weekend-prep + HEAD
  python3 tools/weekend_log.py --since 2026-10-17T00:00 -o docs/NEW_THIS_WEEKEND.md
"""
import argparse, collections, subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def git(*a):
    return subprocess.run(['git', *a], cwd=REPO, capture_output=True, text=True).stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--since', default='2026-10-16T00:00:00-04:00')
    ap.add_argument('--branches', nargs='*', default=['HEAD', 'weekend/parser-ft', 'cloud/weekend-prep', 'origin/cloud/weekend-prep'])
    ap.add_argument('-o', '--out', default=None)
    a = ap.parse_args()
    seen, rows = set(), []
    for br in a.branches:
        if not git('rev-parse', '--verify', '-q', br).strip():
            continue
        for line in git('log', br, f'--since={a.since}', '--date=iso-strict', '--pretty=%H%x09%ad%x09%s', '--shortstat').splitlines() + ['']:
            if '\t' in line:
                sha, date, subj = line.split('\t', 2)
                cur = {'sha': sha[:7], 'date': date, 'subject': subj, 'stat': ''}
                if sha not in seen:
                    seen.add(sha); rows.append(cur)
                else:
                    cur = None
            elif line.strip() and cur is not None:
                cur['stat'] = line.strip()
    rows.sort(key=lambda r: r['date'])
    by_day = collections.OrderedDict()
    for r in rows:
        by_day.setdefault(r['date'][:10], []).append(r)
    out = ['# New this weekend (generated by tools/weekend_log.py)', '', f'{len(rows)} commits since {a.since} across {", ".join(a.branches)}. '
           'Everything before Oct 16 is prior work (GMAPS, Boston Oct 3) and is said so in the pitch.', '']
    for day, rs in by_day.items():
        out += [f'## {day} ({len(rs)} commits)', '', '| time | commit | what | size |', '|---|---|---|---|']
        for r in rs:
            out.append(f"| {r['date'][11:16]} | `{r['sha']}` | {r['subject'][:110]} | {r['stat']} |")
        out.append('')
    text = '\n'.join(out)
    if a.out:
        Path(a.out).write_text(text); print(f'{len(rows)} commits -> {a.out}')
    else:
        print(text)


if __name__ == '__main__':
    main()
